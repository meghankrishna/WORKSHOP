#!/usr/bin/env python3
"""Helper for Lab 3: load a Frida script into a running app and show its output.

You do NOT edit this file. Usage:

    python3 run_frida.py <package> <script.js> [--duration 30] [--config apis_demo.json]

The app must already be open on the emulator.
"""
import argparse
import json
import os
import sys
import time

import frida

HERE = os.path.dirname(os.path.abspath(__file__))


def find_project_root(script_path):
    """Find the folder that holds node_modules/frida-java-bridge (needed by Frida 17+)."""
    folder = os.path.dirname(os.path.abspath(script_path))
    while True:
        if os.path.isdir(os.path.join(folder, "node_modules", "frida-java-bridge")):
            return folder
        parent = os.path.dirname(folder)
        if parent == folder:
            break
        folder = parent
    sys.exit("[-] frida-java-bridge not found. Ask your instructor (it should be installed).")


def find_pid(device, package):
    """Frida lists apps by their display label (e.g. "Settings"), not by package
    name, so look the running app up by its identifier instead."""
    for app in device.enumerate_applications():
        if app.identifier == package and app.pid:
            return app.pid
    return None


def main():
    p = argparse.ArgumentParser()
    p.add_argument("package", help="package name of the app, e.g. com.android.settings")
    p.add_argument("script", help="the .js file to load")
    p.add_argument("--duration", type=int, default=30, help="seconds to watch")
    p.add_argument("--config", help="JSON file passed to the script's init() function")
    args = p.parse_args()

    root = find_project_root(args.script)
    source = frida.Compiler().build(os.path.abspath(args.script), project_root=root)

    def on_message(message, data):
        if message["type"] == "log":
            print(message["payload"])
        elif message["type"] == "send":
            print("[send]", message["payload"])
        elif message["type"] == "error":
            print("[error]", message.get("description"))

    device = frida.get_usb_device(timeout=10)
    print("[+] device:", device.name)
    pid = find_pid(device, args.package)
    if pid is None:
        sys.exit("[-] %s is not running. Open it on the emulator first (frida-ps -Ua lists running apps)." % args.package)
    session = device.attach(pid)
    script = session.create_script(source)
    script.on("message", on_message)
    script.load()

    if args.config:
        with open(args.config) as f:
            script.exports_sync.init(json.load(f))

    print("[+] watching %s for %d s: use the app now (Ctrl+C to stop)\n" % (args.package, args.duration))
    try:
        time.sleep(args.duration)
    except KeyboardInterrupt:
        pass
    finally:
        script.unload()
        session.detach()
        print("\n[+] done")


if __name__ == "__main__":
    main()
